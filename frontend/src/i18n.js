export function translate(key, language = 'fr') {
    return translations[language]?.[key] ?? translations.fr[key] ?? key
}

export function getDirection(language = 'fr') {
    return DIRECTION_MAP[language] ?? 'ltr'
}

export function getLocale(language = 'fr') {
    return LOCALE_MAP[language] ?? 'fr-MA'
}

export function formatCurrency(value, language = 'fr') {
    if (value == null || Number.isNaN(Number(value))) return ''
    return new Intl.NumberFormat(getLocale(language), {
        style: 'currency',
        currency: 'MAD',
        maximumFractionDigits: 0,
    }).format(value)
}

function parseDateValue(value) {
    if (value instanceof Date) return value
    if (typeof value !== 'string') return new Date(value)

    const parsed = new Date(value)
    if (!Number.isNaN(parsed.getTime())) return parsed

    const match = value.match(/^\s*(\d{1,2})\/(\d{1,2})\/(\d{4})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2}))?)?\s*$/)
    if (match) {
        const [, day, month, year, hour = '00', minute = '00', second = '00'] = match
        return new Date(`${year}-${month.padStart(2, '0')}-${day.padStart(2, '0')}T${hour.padStart(2, '0')}:${minute.padStart(2, '0')}:${second.padStart(2, '0')}`)
    }

    return new Date(value)
}

export function formatDate(value, language = 'fr', options = {}) {
    if (!value) return ''
    const date = parseDateValue(value)
    if (Number.isNaN(date.getTime())) return ''
    return date.toLocaleDateString(getLocale(language), {
        day: 'numeric',
        month: 'long',
        year: 'numeric',
        ...options,
    })
}

